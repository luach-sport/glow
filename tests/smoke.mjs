// Quick check in a real browser: every screen and sheet opens without errors; screenshots to tests/shots/.
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const URL = process.env.URL || 'http://localhost:8765/';
mkdirSync('tests/shots', { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 2, colorScheme: process.env.DARK ? 'dark' : 'light' });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto(URL);
await page.waitForTimeout(800);
await page.screenshot({ path: 'tests/shots/welcome.png' });
await page.click('[data-action="finish-welcome"]');
await page.waitForTimeout(1500);
const shot = async (n) => { await page.waitForTimeout(700); await page.screenshot({ path: 'tests/shots/' + n + '.png' }); };
await shot('home');
await page.click('[data-action="change-now"][data-what="all"]'); await shot('home2');
for (const t of ['images', 'quotes', 'store', 'settings']) { await page.click('#tabs [data-tab="' + t + '"]'); await shot(t); }
await page.click('#tabs [data-tab="home"]');
await page.click('[data-action="open-rotation"]'); await shot('rotation');
await page.click('.sheet-head [data-action="close-sheet"]');
await page.click('[data-sheet="style"]'); await shot('style');
await page.click('[data-action="style-set"][data-v="top"]'); await page.click('[data-action="style-set"][data-k="band"][data-v="none"]'); await shot('style2');
await page.click('.sheet-head [data-action="close-sheet"]');
await page.click('[data-sheet="history"]'); await shot('history');
await page.click('.sheet-head [data-action="close-sheet"]');
await page.click('#tabs [data-tab="images"]');
await page.click('.g-item >> nth=3'); await shot('image');
await page.click('[data-action="fav-image"]'); await page.click('[data-action="image-now"] >> nth=0'); await page.waitForTimeout(400);
await page.click('#tabs [data-tab="quotes"]');
await page.click('[data-action="new-quote"] >> nth=0'); await page.fill('#qt', 'זה משפט בדיקה שלי'); await page.click('[data-action="save-quote"]'); await shot('quotes-mine');
await page.click('.q-main >> nth=0'); await shot('quote');
await page.click('.sheet-head [data-action="close-sheet"]');
await page.fill('#q-search', 'כוח'); await shot('search');
await page.click('#tabs [data-tab="settings"]'); await page.click('[data-action="set-mode"][data-v="separate"]'); await page.waitForTimeout(500);
await page.click('#tabs [data-tab="home"]'); await shot('home-separate');
console.log(errors.length ? errors.join('\n') : 'no errors');
await browser.close();
