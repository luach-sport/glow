// Quick check in a real browser: every screen and sheet opens without errors; screenshots to tests/shots/.
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const URL = process.env.URL || 'http://localhost:8765/';
mkdirSync('tests/shots', { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 2, colorScheme: process.env.DARK ? 'dark' : 'light' });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/TUNNEL|ERR_/.test(m.text())) errors.push('console: ' + m.text()); });
await page.goto(URL);
await page.waitForTimeout(800);
const shot = async (n, full) => { await page.waitForTimeout(700); await page.screenshot({ path: 'tests/shots/' + n + '.png', fullPage: !!full }); };
const close = () => page.click('.sheet-head [data-action="close-sheet"]');
await shot('welcome');
await page.click('[data-action="wel-walls"][data-v="home"]');
await page.click('[data-action="finish-welcome"]');
await page.waitForTimeout(2500);
await shot('home', true);
await page.click('[data-action="change-now"][data-what="quote"] >> nth=0'); await page.waitForTimeout(400);
await page.click('[data-sheet="qset"]'); await shot('qset');
await page.click('[data-action="q-mode"][data-v="interval"]'); await shot('qset2');
await close();
await page.click('[data-sheet="widget"] >> nth=0'); await shot('widget');
await page.click('[data-action="w-look"][data-v="brand"]'); await shot('widget2');
await close();
await page.click('[data-sheet="walls"]'); await shot('walls');
await page.click('[data-action="wall-screen"][data-v="lock"]'); await page.waitForTimeout(400);
await page.click('[data-action="wall-same"][data-v="separate"]'); await shot('walls2');
await close();
await page.click('[data-action="toggle-walls"]'); await page.waitForTimeout(500); await shot('walls-off');
await close();
await shot('home-off', true);
await page.click('[data-sheet="history"]'); await shot('history');
await close();
for (const t of ['images', 'quotes', 'store', 'settings']) { await page.click('#tabs [data-tab="' + t + '"]'); await shot(t); }
await page.click('#tabs [data-tab="quotes"]');
await page.click('[data-action="toggle-arrange"]'); await page.click('[data-action="q-move"][data-d="1"] >> nth=0'); await shot('arrange');
await page.click('[data-action="toggle-arrange"]');
await page.click('.q-main >> nth=2'); await shot('quote');
await page.click('[data-action="quote-now"]'); await page.waitForTimeout(400);
await page.click('#tabs [data-tab="images"]'); await page.click('.g-item >> nth=3'); await shot('image');
await page.click('[data-action="image-now"] >> nth=0'); await page.waitForTimeout(600);
await page.click('#tabs [data-tab="home"]'); await shot('home-final', true);
console.log(errors.length ? errors.join('\n') : 'no errors');
await browser.close();
